"""Pinned upstream RPC docs: method extraction, drift, integrity and redaction."""
from __future__ import annotations

from copy import deepcopy
import hashlib
import json
from pathlib import Path
import os
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from verify_zallet_upstream_contract import (
    METHODS, UpstreamInputError, extract_contract, read_upstream, verify, MAX_SOURCE_BYTES,
)


class ZalletPinnedContractTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.contract = json.loads((ROOT / 'tests/fixtures/rpc/zallet-pczt-lifecycle-contract.json').read_text())
        cls.provenance = json.loads((ROOT / 'tests/fixtures/rpc/zallet-v0.1.0-beta.3-provenance.json').read_text())
        cls.sample = cls.make_sample(cls.contract)

    @staticmethod
    def make_sample(contract: dict) -> str:
        parts = ['<!-- @generated by test reference; no upstream bytes -->\n']
        for method in contract['methods']:
            parts.extend([f"## `{method['name']}`\n", '\nSynthetic generated reference.\n'])
            if method['name'] == 'rpc.discover':
                continue
            parts.append('\n#### Arguments\n')
            for param in method['params']:
                flag = 'required' if param['required'] else 'optional'
                parts.append(f"- `{param['name']}` (string, {flag}) synthetic contract.\n")
                if param['name'] == 'amounts':
                    parts.append('  - `address` (string, required) nested recipient, NOT top-level.\n')
        return ''.join(parts)

    def test_extracts_real_shape_without_nested_recipient_fields(self):
        actual = extract_contract(self.sample)
        self.assertEqual(actual, self.contract)
        self.assertEqual(tuple(item['name'] for item in actual['methods']), METHODS)
        create = next(x for x in actual['methods'] if x['name'] == 'pczt_create')
        self.assertNotIn('address', [p['name'] for p in create['params']])

    def test_extractor_fails_on_duplicate_or_missing_methods(self):
        for edited in (self.sample.replace('## `pczt_sign`', '## `pczt_prove`'),
                       self.sample.replace('## `pczt_create`', '## `bad_create`'),
                       self.sample.replace('#### Arguments', '#### INVALID', 1),
                       self.sample.replace('- `pczt` (string, required)', '- `pczt` (invalid)', 1),
                       self.sample.replace('<!-- @generated by', 'USER INSTRUCTIONS')):
            with self.subTest(edited=edited[:32]), self.assertRaises(UpstreamInputError):
                extract_contract(edited)

    def test_pinned_digest_rejects_modified_source(self):
        source = self.sample.encode()
        meta = {**self.provenance, 'sha256': hashlib.sha256(source).hexdigest()}
        self.assertTrue(verify(source, meta, self.contract)['passed'])
        with self.assertRaises(UpstreamInputError):
            verify(source + b'private-marker', meta, self.contract)
        with self.assertRaises(UpstreamInputError):
            verify(source, {**meta, 'commit': '0' * 40}, self.contract)

    def test_contract_drift_is_machine_readable(self):
        source = self.sample.encode()
        meta = {**self.provenance, 'sha256': hashlib.sha256(source).hexdigest()}
        changed = deepcopy(self.contract)
        changed['methods'] = [x for x in changed['methods'] if x['name'] != 'pczt_prove']
        with self.assertRaises(UpstreamInputError):
            verify(source, meta, changed)
        # A change to an existing contract parameter must trigger a finding.
        changed = deepcopy(self.contract)
        sign = next(x for x in changed['methods'] if x['name'] == 'pczt_sign')
        sign['params'][0]['name'] = 'changed_pczt'
        result = verify(source, meta, changed)
        self.assertFalse(result['passed'])
        self.assertIn('RPC-PARAMETER-MISSING', [x['rule'] for x in result['findings']])

    def test_rejects_symlinks_special_files_and_oversize(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            real = root / 'source.md'
            real.write_text(self.sample)
            self.assertEqual(read_upstream(real), self.sample.encode())
            link = root / 'link.md'
            link.symlink_to(real)
            for path in (link, root):
                with self.assertRaises(UpstreamInputError):
                    read_upstream(path)
            huge = root / 'huge.md'
            with huge.open('wb') as handle:
                handle.truncate(MAX_SOURCE_BYTES + 1)
            with self.assertRaises(UpstreamInputError):
                read_upstream(huge)
            if hasattr(os, 'mkfifo'):
                fifo = root / 'fifo'
                os.mkfifo(fifo)
                with self.assertRaises(UpstreamInputError):
                    read_upstream(fifo)

    def test_cli_does_not_echo_altered_upstream_bytes(self):
        with tempfile.TemporaryDirectory() as temp:
            file = Path(temp) / 'PRIVATE_DO_NOT_ECHO.md'
            file.write_text(self.sample + '\nFAKE_PRIVATE_MARKER\n')
            result = subprocess.run([sys.executable, str(ROOT / 'scripts/verify_zallet_upstream_contract.py'),
                                     '--source', str(file), '--json'], capture_output=True,
                                    text=True, timeout=10)
            self.assertEqual(result.returncode, 1)
            self.assertFalse(result.stdout)
            self.assertNotIn('PRIVATE_DO_NOT_ECHO', result.stderr)
            self.assertNotIn('FAKE_PRIVATE_MARKER', result.stderr)

    def test_exact_release_source_if_supplied(self):
        source = os.environ.get('ZALLET_PINNED_RPC_SOURCE')
        if not source:
            self.skipTest('Provide ZALLET_PINNED_RPC_SOURCE for upstream release evidence run')
        report = verify(read_upstream(Path(source)), self.provenance, self.contract)
        self.assertTrue(report['passed'])
        self.assertEqual(report['checked_methods'], 7)
        self.assertEqual(report['finding_count'], 0)


if __name__ == '__main__':
    unittest.main()
