//! SARIF 2.1.0 export from already-validated, local Rust PCZT reports.
//!
//! No original PCZT bytes, source path, file content, addresses or transaction
//! values are accepted by this module. We intentionally use logical locations
//! rather than pretending a binary PCZT field has a repository source line.
use serde_json::{json, Value};
use std::collections::BTreeSet;
use zerynex::{Report, StageComparison};

const RULES: [(&str, &str); 8] = [
    (
        "PCZT-GLOBAL-METADATA",
        "Global proprietary metadata is present",
    ),
    (
        "PCZT-TRANSPARENT-INPUTS",
        "Transparent inputs prohibited by policy",
    ),
    (
        "PCZT-TRANSPARENT-OUTPUTS",
        "Transparent outputs prohibited by policy",
    ),
    (
        "PCZT-UNREVIEWED-METADATA",
        "Unreviewed field-level proprietary metadata",
    ),
    (
        "PCZT-RESTRICTED-DISCLOSURE",
        "Field prohibited by restricted handoff policy",
    ),
    (
        "PCZT-SAPLING-POLICY",
        "Sapling components prohibited by application policy",
    ),
    (
        "PCZT-DUMMY-KEY",
        "Intermediate dummy signing key is present",
    ),
    (
        "PCZT-STRUCTURE-DRIFT",
        "PCZT component count changed between stages",
    ),
];

fn safe_field(field: &str) -> String {
    // Field paths are generated by Zerynex, but this check also prevents
    // accidentally displaying a future untrusted value in a SARIF artifact.
    if field.len() <= 500
        && !field.is_empty()
        && field
            .bytes()
            .all(|ch| ch.is_ascii_alphanumeric() || b".[]_-".contains(&ch))
    {
        field.to_owned()
    } else {
        "redacted".to_owned()
    }
}

fn supported_rule(rule: &str) -> Result<&'static str, &'static str> {
    RULES
        .iter()
        .find(|(known, _)| *known == rule)
        .map(|(name, _)| *name)
        .ok_or("Unknown SARIF rule; update the reviewed rule catalog")
}

fn result(rule: &str, field: &str, kind: &str, is_new: bool) -> Result<Value, &'static str> {
    let rule = supported_rule(rule)?;
    let field = safe_field(field);
    Ok(json!({
        "ruleId": rule,
        "level": if rule == "PCZT-STRUCTURE-DRIFT" { "error" } else { "warning" },
        "message": {"text": "Review a Zerynex PCZT disclosure-policy observation. Structural checks do not verify signatures, proofs or transaction equivalence."},
        "locations": [{"logicalLocations": [{
            "name": field,
            "fullyQualifiedName": format!("pczt::{field}"),
            "kind": "member"
        }]}],
        "properties": {"pczt_field": field, "category": kind, "new_in_candidate": is_new}
    }))
}

fn document(results: Vec<Value>, passed: bool, compared: bool) -> Value {
    let rules: Vec<Value> = RULES
        .iter()
        .map(|(id, description)| {
            json!({
                "id": id,
                "shortDescription": {"text": description},
                "help": {"text": "A structural PCZT policy observation; review locally. Never upload confidential wallet artifacts or use this as signing authorization."}
            })
        })
        .collect();
    json!({
        "version": "2.1.0",
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "runs": [{
            "tool": {"driver": {
                "name": "Zerynex",
                "version": env!("CARGO_PKG_VERSION"),
                "informationUri": "https://github.com/Oluwa-Laughter/zerynex",
                "rules": rules
            }},
            "invocations": [{"executionSuccessful": true}],
            "results": results,
            "properties": {
                "zerynexPassed": passed,
                "stageComparison": compared,
                "publicCIRequiresSyntheticFixtures": true,
                "limitation": "Selected structural disclosure checks; no transaction bytes, source paths, private fields, signing or proof verification."
            }
        }]
    })
}

pub fn analysis(report: &Report) -> Result<Value, &'static str> {
    let results: Vec<Value> = report
        .findings
        .iter()
        .map(|item| result(item.rule, &item.field, "policy", false))
        .collect::<Result<_, _>>()?;
    Ok(document(results, report.passed(), false))
}

pub fn comparison(after: &Report, stage: &StageComparison) -> Result<Value, &'static str> {
    let additions: BTreeSet<(&str, &str)> = stage
        .added_findings
        .iter()
        .map(|item| (item.rule, item.field.as_str()))
        .collect();
    // Also include pre-existing violations. Otherwise SARIF could contain no
    // findings even when the stage comparator correctly exits status 2.
    let mut results: Vec<Value> = after
        .findings
        .iter()
        .map(|item| {
            result(
                item.rule,
                &item.field,
                "policy",
                additions.contains(&(item.rule, item.field.as_str())),
            )
        })
        .collect::<Result<_, _>>()?;
    results.extend(
        stage
            .component_deltas
            .iter()
            .map(|item| result("PCZT-STRUCTURE-DRIFT", item.component, "stage_drift", true))
            .collect::<Result<Vec<_>, _>>()?,
    );
    Ok(document(results, stage.passed, true))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn field_rejects_values_not_structural_paths() {
        assert_eq!(
            safe_field("orchard.actions[0].spend.dummy_sk"),
            "orchard.actions[0].spend.dummy_sk"
        );
        assert_eq!(safe_field("wallet address z1Secret"), "redacted");
        assert_eq!(safe_field("global.proprietary\nPRIVACY_MARKER"), "redacted");
        assert_eq!(safe_field(&"a".repeat(501)), "redacted");
    }

    #[test]
    fn known_rules_are_bounded() {
        assert!(supported_rule("unknown from input").is_err());
        assert_eq!(RULES.len(), 8);
    }
}
