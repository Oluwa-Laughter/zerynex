#!/usr/bin/env python3
"""Verify PCZT method declarations against immutable upstream Zallet docs.

Requires a manually downloaded/generated markdown file from one pinned
upstream commit. This tool never downloads data, calls an RPC endpoint,
reads a wallet or returns the source text to stdout/stderr.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys

# Import the Python package implementation also used by the installed CLI/MCP.
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages/python/src"))
from zerynex_py.rpc_contract import ContractInputError, compare, parse_methods, read_json, MAX_CONTRACT  # noqa: E402

PROVENANCE = ROOT / "tests/fixtures/rpc/zallet-v0.1.0-beta.3-provenance.json"
METHODS = ("rpc.discover", "pczt_create", "pczt_combine", "pczt_inspect",
           "pczt_prove", "pczt_sign", "pczt_extract")
METHOD_HEADING = re.compile(r'^## `([^`\n]+)`\s*$', flags=re.MULTILINE)
TOP_LEVEL_PARAM = re.compile(r'^- `([A-Za-z_][A-Za-z0-9_]*)` \([^\n)]*?\b(required|optional)\b[^\n)]*\)', flags=re.MULTILINE)
MAX_SOURCE_BYTES = 256 * 1024


class UpstreamInputError(Exception):
    """Safe failure type that never reflects untrusted upstream content."""


def extract_contract(source: str) -> dict:
    """Extract only ordered PCZT parameter names and required flags.

    The upstream book contains nested example recipient fields, which are
    deliberately not JSON-RPC parameters. Only left-aligned list bullets
    inside each method's Arguments section count.
    """
    if not isinstance(source, str) or not source.startswith('<!-- @generated by'):
        raise UpstreamInputError
    headings = list(METHOD_HEADING.finditer(source))
    if len(headings) < len(METHODS) or len({h.group(1) for h in headings}) != len(headings):
        raise UpstreamInputError
    found = {}
    for index, heading in enumerate(headings):
        name = heading.group(1)
        if name not in METHODS:
            continue
        end = headings[index + 1].start() if index + 1 < len(headings) else len(source)
        body = source[heading.end():end]
        if name == 'rpc.discover':
            if '#### Arguments' in body:
                raise UpstreamInputError
            found[name] = []
            continue
        if body.count('#### Arguments') != 1:
            raise UpstreamInputError
        section = body.split('#### Arguments', 1)[1].split('\n#### ', 1)[0]
        matches = list(TOP_LEVEL_PARAM.finditer(section))
        raw_top_level = [line for line in section.splitlines() if line.startswith('- `')]
        if not matches or len(matches) != len(raw_top_level):
            raise UpstreamInputError
        parameters = [{'name':m.group(1), 'required':m.group(2) == 'required'} for m in matches]
        if len(parameters) != len({p['name'] for p in parameters}):
            raise UpstreamInputError
        found[name] = parameters
    if set(found) != set(METHODS):
        raise UpstreamInputError
    return {'version':1, 'methods':[{'name':name, 'params':found[name]} for name in METHODS]}


def read_upstream(path: Path) -> bytes:
    """Fail closed on symlinks, nonregular files and unbounded source reads."""
    try:
        if path.is_symlink():
            raise UpstreamInputError
        flags = os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0) | getattr(os, 'O_NONBLOCK', 0)
        fd = os.open(path, flags)
        with os.fdopen(fd, 'rb') as handle:
            metadata = os.fstat(handle.fileno())
            if not stat.S_ISREG(metadata.st_mode) or not 0 < metadata.st_size <= MAX_SOURCE_BYTES:
                raise UpstreamInputError
            content = handle.read(MAX_SOURCE_BYTES + 1)
        if len(content) > MAX_SOURCE_BYTES:
            raise UpstreamInputError
        return content
    except (OSError, UpstreamInputError):
        raise UpstreamInputError from None


def verify(source: bytes, provenance: dict, contracted: dict) -> dict:
    if (type(provenance.get('version')) is not int or provenance['version'] != 1 or
            provenance.get('release') != 'v0.1.0-beta.3' or
            provenance.get('commit') != '987382f67e622915228686e9f956c6a9c9a7514c' or
            provenance.get('upstream') != 'zcash/zallet' or
            provenance.get('path') != 'book/src/rpc/methods.md' or
            provenance.get('contract') != 'tests/fixtures/rpc/zallet-pczt-lifecycle-contract.json' or
            not re.fullmatch(r'[0-9a-f]{64}', str(provenance.get('sha256', '')))):
        raise UpstreamInputError
    digest = hashlib.sha256(source).hexdigest()
    if digest != provenance['sha256']:
        raise UpstreamInputError
    try:
        # Baseline scope cannot be quietly narrowed by changing the local
        # contract. This gate attests to all seven methods, not a subset.
        declared = parse_methods(contracted, contract=True)
        if tuple(declared) != METHODS:
            raise UpstreamInputError
        actual = extract_contract(source.decode('utf-8'))
        # Check the extracted declarations against the maintained contract;
        # strict mode rejects new required params and missing contract fields.
        result = compare({'openrpc': '1.3.2', 'methods': actual['methods']},
                         contracted, deny_new_required=True)
        # Ensure exact covered method count; no other methods are claimed.
        passed = result['passed'] and result['checked_methods'] == len(METHODS)
    except (UnicodeError, ContractInputError, UpstreamInputError):
        raise UpstreamInputError from None
    return {
        'passed': bool(passed),
        'release': provenance['release'],
        'source_commit': provenance['commit'],
        'source_sha256': digest,
        'checked_methods': result['checked_methods'],
        'finding_count': result['finding_count'],
        'findings': result['findings'],
        'evidence': 'Verified against release-pinned generated RPC documentation, not a running Zallet binary.',
        'limitations': 'No live rpc.discover, PCZT producer/prover/signer output, proof verification or transaction semantics tested.',
    }


def main() -> int:
    parser = argparse.ArgumentParser(description='Compare a pinned Zallet RPC book export with the local PCZT contract')
    parser.add_argument('--source', required=True, type=Path, help='Previously obtained local upstream methods.md')
    parser.add_argument('--json', action='store_true')
    args = parser.parse_args()
    try:
        provenance = read_json(str(PROVENANCE), 8192)
        contract = read_json(str(ROOT / provenance['contract']), MAX_CONTRACT)
        report = verify(read_upstream(args.source), provenance, contract)
    except (UpstreamInputError, ContractInputError, ValueError, KeyError, TypeError):
        print('Zerynex: release-pinned upstream evidence missing, altered or invalid.', file=sys.stderr)
        return 1
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print('Pinned Zallet RPC contract:', 'PASS' if report['passed'] else 'DRIFT')
        print('Methods checked:', report['checked_methods'])
        print('Findings:', report['finding_count'])
    return 0 if report['passed'] else 2


if __name__ == '__main__':
    raise SystemExit(main())
