#!/usr/bin/env python3
"""Generate distributable SDK rule metadata from one versioned canonical JSON.

Never downloads, processes PCZT bytes, accepts instructions from the input,
or reads private data. --check fails on drift without writing anything.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'rules/catalog.json'
TARGETS = (
    ROOT / 'packages/python/src/zerynex_py/fixtures/rule-catalog.json',
    ROOT / 'packages/sdk/src/rule-catalog.ts',
    ROOT / 'packages/sdk/src/rule-catalog.js',
)


def verified_catalog() -> dict:
    raw = SOURCE.read_bytes()
    if not 0 < len(raw) < 32 * 1024:
        raise ValueError('Invalid public rule registry size.')
    # Disallow duplicate keys at any nesting depth, including malicious records.
    def unique(pairs):
        output = {}
        for key, val in pairs:
            if key in output:
                raise ValueError('Duplicate key in rule catalog.')
            output[key] = val
        return output
    data = json.loads(raw, object_pairs_hook=unique)
    if (set(data) != {'schema_version','tool','rule_set_version','scope','rules'} or
            type(data['schema_version']) is not int or data['schema_version'] != 1 or
            data['tool'] != 'zerynex' or data['rule_set_version'] != '1.0.0' or
            not isinstance(data['scope'], str) or not 20 < len(data['scope']) <= 512):
        raise ValueError('Invalid versioned rule registry.')
    rules = data['rules']
    if not isinstance(rules,list) or not 1 <= len(rules) <= 32:
        raise ValueError('Invalid rules count.')
    ids = []
    for item in rules:
        if not isinstance(item,dict) or set(item) != {'id','title','severity','category','applies_to','summary'}:
            raise ValueError('Invalid rule declaration.')
        if (not isinstance(item['id'],str) or not re.fullmatch('PCZT-[A-Z-]{3,64}',item['id']) or
                item['severity'] not in ('warning','error') or
                item['category'] not in ('metadata','pool_policy','handoff','regression') or
                not isinstance(item['title'],str) or not 5 <= len(item['title']) <= 120 or
                not isinstance(item['summary'],str) or not 10 <= len(item['summary']) <= 256 or
                item['applies_to'] not in (['stage_comparison'],['analysis','stage_comparison'])):
            raise ValueError('Invalid reviewed rule metadata.')
        ids.append(item['id'])
    if ids != sorted(set(ids)):
        raise ValueError('Rule identifiers must be unique and sorted.')
    return data


def outputs(data: dict) -> dict[Path,str]:
    text = json.dumps(data,indent=2,ensure_ascii=True)+'\n'
    ts = '// GENERATED by scripts/sync-rule-catalog.py; edit rules/catalog.json instead.\n'
    ts += 'export const RULE_CATALOG = '+json.dumps(data,indent=2,ensure_ascii=True)+' as const\n'
    ts += 'export type RuleId = (typeof RULE_CATALOG.rules)[number]["id"]\n'
    ts += 'export type RuleDefinition = (typeof RULE_CATALOG.rules)[number]\n'
    ts += 'export function getRule(id: string): RuleDefinition | undefined {\n'
    ts += '  return RULE_CATALOG.rules.find(rule => rule.id === id)\n}\n'
    js = '// GENERATED by scripts/sync-rule-catalog.py; edit rules/catalog.json instead.\n'
    js += 'export const RULE_CATALOG = '+json.dumps(data,indent=2,ensure_ascii=True)+'\n'
    js += 'export function getRule(id) {\n'
    js += '  return RULE_CATALOG.rules.find(rule => rule.id === id)\n}\n'
    return {TARGETS[0]:text, TARGETS[1]:ts, TARGETS[2]:js}


def main() -> int:
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    try:
        generated=outputs(verified_catalog())
        for path,content in generated.items():
            if args.check:
                if not path.is_file() or path.read_text()!=content:
                    raise ValueError('SDK rule catalog snapshot is out of sync.')
            else:
                path.parent.mkdir(parents=True,exist_ok=True)
                path.write_text(content)
    except (OSError,ValueError,TypeError):
        print('Zerynex rule catalog is malformed or SDK snapshots differ.',file=sys.stderr)
        return 1
    print('Rule catalog: SDK snapshots verified' if args.check else 'Rule catalog: SDK snapshots generated')
    return 0


if __name__=='__main__':
    raise SystemExit(main())
